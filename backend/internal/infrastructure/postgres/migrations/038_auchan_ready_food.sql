valid AS (
    SELECT
        btrim(name) AS name,
        calories,
        protein,
        fat,
        carbohydrate,
        0.72 + 0.05 * (
            (calories IS NOT NULL)::INTEGER +
            (protein IS NOT NULL)::INTEGER +
            (fat IS NOT NULL)::INTEGER +
            (carbohydrate IS NOT NULL)::INTEGER
        ) AS data_quality
    FROM source
    WHERE btrim(name) <> ''
      AND (calories IS NOT NULL OR protein IS NOT NULL OR fat IS NOT NULL OR carbohydrate IS NOT NULL)
      AND (calories IS NULL OR calories BETWEEN 0 AND 1000)
      AND (protein IS NULL OR protein BETWEEN 0 AND 100)
      AND (fat IS NULL OR fat BETWEEN 0 AND 100)
      AND (carbohydrate IS NULL OR carbohydrate BETWEEN 0 AND 100)
)
